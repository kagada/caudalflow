import { describe, expect, it } from 'vitest';
import { markdownSelection } from '../markdownSelection';

describe('Markdown selection preserves boundary formatting', () => {
  it.each([
    ['我**突然**想', '突然', '**突然**'],
    ['我**突然**想', '突然**想', '**突然**想'],
    ['我**突然**想', '我**突然', '我**突然**'],
    ['我**突然**想', '我**突然**想', '我**突然**想'],
    ['我**突然**想', '突', '**突**'],
    ['我**突然**想', '然', '**然**'],
    ['我 __突然__ 想', '突然', '__突然__'],
    ['我*突然*想', '突然', '*突然*'],
    ['我~~突然~~想', '突然', '~~突然~~'],
    ['我**突*然*想**到', '然', '***然***'],
    ['我[突然](https://example.com)想', '突然', '[突然](https://example.com)'],
    ['我[突然](https://example.com)想', '然', '[然](https://example.com)'],
    ['我`突然`想', '突然', '`突然`'],
    ['我**突然**想', '想', '想'],
    ['我**突然**想', '我', '我'],
    ['## 摘要（选中文字）', '摘要（选中文字）', '## 摘要（选中文字）'],
    ['### 摘要（选中文字）', '选中文字', '### 选中文字'],
    ['## 摘要 ##', '摘要', '## 摘要 ##'],
    ['摘要\n====', '摘要', '摘要\n===='],
    ['- 动作：通宵修理；游丝逐根理顺；齿轮擦洗', '动作：通宵修理；游丝逐根理顺；齿轮擦洗', '- 动作：通宵修理；游丝逐根理顺；齿轮擦洗'],
    ['* 动作：**通宵修理**', '通宵修理', '* **通宵修理**'],
    ['1. 动作\n2. 结果', '结果', '2. 结果'],
    ['- [x] 完成事项', '完成事项', '- [x] 完成事项'],
    ['- [ ] 待办事项', '事项', '- [ ] 事项'],
    ['> 引用文字', '引用', '> 引用'],
    ['> 引用文字\n> 第二行', '第二行', '> 第二行'],
    ['``**突然**``', '突然', '``突然``'],
    ['`# 标题`', '标题', '`标题`'],
    ['`- 列表`', '列表', '`列表`'],
    ['- 父项\n  - 子项', '子项', '- 子项'],
    ['- 父项\n  - 子项', '父项\n  - 子项', '- 父项\n  - 子项'],
    ['- 第一项\n- 第二项', '一项\n- 第二', '- 一项\n- 第二'],
  ])('copies %s / %s with complete wrappers', (content, selected, expected) => {
    const start = content.indexOf(selected);
    expect(markdownSelection(content, start, start + selected.length)).toBe(expected);
  });
});
